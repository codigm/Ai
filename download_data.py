import os
import urllib.request
import zipfile
import json
import hashlib
import shutil

REPOS = [
    {"repo": "python/cpython", "branch": "main", "license": "Python"},
    {"repo": "facebook/react", "branch": "main", "license": "MIT"},
    {"repo": "spring-projects/spring-framework", "branch": "main", "license": "Apache-2.0"},
]

MAX_FILE_SIZE = 500 * 1024 # 500 KB
CORPUS_DIR = "corpus"
MANIFEST_FILE = "manifest.jsonl"
TEMP_DIR = "temp_repos"

def is_vendor_path(path):
    parts = path.replace('\\', '/').split('/')
    vendor_dirs = {'vendor', 'deps', 'third_party', '3rdparty'}
    return any(p in vendor_dirs for p in parts)

def is_generated(content):
    # Check first few lines for generated warnings
    lines = content.split('\n')[:10]
    for line in lines:
        lower_line = line.lower()
        if 'auto-generated' in lower_line or 'autogenerated' in lower_line or 'generated by' in lower_line:
            return True
    return False

def download_and_extract(repo_info):
    repo = repo_info["repo"]
    branch = repo_info["branch"]
    
    url = f"https://github.com/{repo}/archive/refs/heads/{branch}.zip"
    print(f"Downloading {repo} from {url}...")
    
    zip_path = os.path.join(TEMP_DIR, f"{repo.replace('/', '_')}.zip")
    
    try:
        # Use a user-agent to avoid 403 Forbidden from GitHub API sometimes
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        with urllib.request.urlopen(req) as response, open(zip_path, 'wb') as out_file:
            shutil.copyfileobj(response, out_file)
    except Exception as e:
        print(f"Failed to download {repo}: {e}")
        return None
    
    extract_path = os.path.join(TEMP_DIR, repo.replace('/', '_'))
    with zipfile.ZipFile(zip_path, 'r') as zip_ref:
        zip_ref.extractall(extract_path)
        
    os.remove(zip_path)
    return extract_path

def main():
    if os.path.exists(CORPUS_DIR):
        print(f"Clearing old {CORPUS_DIR} directory...")
        shutil.rmtree(CORPUS_DIR)
        
    os.makedirs(CORPUS_DIR)
        
    if not os.path.exists(TEMP_DIR):
        os.makedirs(TEMP_DIR)
        
    seen_hashes = set()
    manifest_entries = []
    
    total_files = 0
    total_size = 0
    
    for repo_info in REPOS:
        extract_path = download_and_extract(repo_info)
        if not extract_path:
            continue
            
        repo_name = repo_info["repo"]
        print(f"Processing {repo_name}...")
        
        for root, _, files in os.walk(extract_path):
            if is_vendor_path(root):
                continue
                
            for file in files:
                if not file.endswith(('.py', '.js', '.java')):
                    continue
                    
                file_path = os.path.join(root, file)
                
                # Check size
                if os.path.getsize(file_path) > MAX_FILE_SIZE:
                    continue
                    
                try:
                    with open(file_path, 'r', encoding='utf-8') as f:
                        content = f.read()
                except UnicodeDecodeError:
                    continue # Skip non-UTF8
                    
                if is_generated(content):
                    continue
                    
                file_hash = hashlib.sha256(content.encode('utf-8')).hexdigest()
                
                if file_hash in seen_hashes:
                    continue
                    
                seen_hashes.add(file_hash)
                
                # Copy to corpus
                safe_repo = repo_name.replace('/', '_')
                new_filename = f"{safe_repo}_{file_hash[:8]}_{file}"
                dest_path = os.path.join(CORPUS_DIR, new_filename)
                
                with open(dest_path, 'w', encoding='utf-8') as f:
                    f.write(content)
                    
                # Relative path in original repo
                rel_path = os.path.relpath(file_path, extract_path)
                # the extracted folder usually has a top-level dir like 'zig-master'
                parts = rel_path.replace('\\', '/').split('/', 1)
                orig_path = parts[1] if len(parts) > 1 else rel_path
                
                manifest_entries.append({
                    "repo": repo_name,
                    "license": repo_info["license"],
                    "file_path": orig_path,
                    "hash": file_hash,
                    "size_bytes": len(content.encode('utf-8'))
                })
                
                total_files += 1
                total_size += len(content.encode('utf-8'))
                
    # Write manifest
    with open(MANIFEST_FILE, 'w', encoding='utf-8') as f:
        for entry in manifest_entries:
            f.write(json.dumps(entry) + '\n')
            
    # Cleanup temp
    shutil.rmtree(TEMP_DIR)
    
    print("\n--- Collection Summary ---")
    print(f"Total valid source files: {total_files}")
    print(f"Total corpus size: {total_size / (1024*1024):.2f} MB")
    print(f"Manifest written to {MANIFEST_FILE}")

if __name__ == "__main__":
    main()
